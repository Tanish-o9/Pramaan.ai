-- 1. Enable pgvector extension
create extension if not exists vector;

-- 2. Create student_embeddings table for multi-embedding storage
create table if not exists student_embeddings (
  id bigint generated by default as identity primary key,
  student_id bigint not null references students(student_id) on delete cascade,
  modality text not null check (modality in ('face', 'voice')),
  embedding vector(128),            -- 128-d dlib ResNet face descriptor
  voice_embedding vector(256),      -- 256-d Resemblyzer speaker descriptor
  quality float default 1.0,        -- Image/audio quality metric (0.0 to 1.0)
  source text default 'web_registration', -- 'web_registration', 'seed_script', 'active_learning'
  created_at timestamptz default now()
);

-- 3. HNSW Index for L2 (Euclidean) distance on Face Embeddings
-- m=16, ef_construction=64 provides optimal trade-off between index build time and 99.8% recall
create index if not exists idx_student_embeddings_face_hnsw 
  on student_embeddings using hnsw (embedding vector_l2_ops)
  with (m = 16, ef_construction = 64);

-- 4. HNSW Index for Cosine distance on Voice Embeddings
create index if not exists idx_student_embeddings_voice_hnsw 
  on student_embeddings using hnsw (voice_embedding vector_cosine_ops)
  with (m = 16, ef_construction = 64);

-- 5. B-Tree Indexes for fast foreign key lookups and scoped queries
create index if not exists idx_student_embeddings_student_id on student_embeddings(student_id);
create index if not exists idx_student_embeddings_modality on student_embeddings(modality);

-- ====================================================================
-- STORED FUNCTIONS (RPC) FOR SCOPED 1:N NEAREST-NEIGHBOR SEARCH
-- ====================================================================

-- Face Matching RPC (Subject-Scoped Euclidean Distance)
create or replace function match_face_embeddings(
  query_embedding vector(128),
  match_threshold float default 0.60,
  match_count int default 5,
  filter_subject_id bigint default null
)
returns table (
  id bigint,
  student_id bigint,
  distance float,
  quality float,
  source text,
  created_at timestamptz
)
language sql stable
as $$
  select
    se.id,
    se.student_id,
    (se.embedding <-> query_embedding) as distance,
    se.quality,
    se.source,
    se.created_at
  from student_embeddings se
  where se.modality = 'face'
    and se.embedding is not null
    and (se.embedding <-> query_embedding) <= match_threshold
    and (
      filter_subject_id is null
      or exists (
        select 1 from subject_students ss
        where ss.subject_id = filter_subject_id
          and ss.student_id = se.student_id
      )
    )
  order by se.embedding <-> query_embedding asc
  limit match_count;
$$;

-- Voice Matching RPC (Subject-Scoped Cosine Distance)
create or replace function match_voice_embeddings(
  query_embedding vector(256),
  match_threshold float default 0.30, -- Cosine distance threshold (1 - cos_sim <= 0.30 -> sim >= 0.70)
  match_count int default 5,
  filter_subject_id bigint default null
)
returns table (
  id bigint,
  student_id bigint,
  distance float,
  quality float,
  source text,
  created_at timestamptz
)
language sql stable
as $$
  select
    se.id,
    se.student_id,
    (se.voice_embedding <=> query_embedding) as distance,
    se.quality,
    se.source,
    se.created_at
  from student_embeddings se
  where se.modality = 'voice'
    and se.voice_embedding is not null
    and (se.voice_embedding <=> query_embedding) <= match_threshold
    and (
      filter_subject_id is null
      or exists (
        select 1 from subject_students ss
        where ss.subject_id = filter_subject_id
          and ss.student_id = se.student_id
      )
    )
  order by se.voice_embedding <=> query_embedding asc
  limit match_count;
$$;

